-- 创建销售发票表
CREATE TABLE sales_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES companies(id),
    buyer_id BIGINT NOT NULL REFERENCES companies(id),
    seller_name VARCHAR(255) NOT NULL,
    buyer_name VARCHAR(255) NOT NULL,
    total_amount DECIMAL(15,2) NOT NULL CHECK (total_amount >= 0),
    invoice_date DATE NOT NULL,
    invoice_number VARCHAR(100),
    invoice_url TEXT,
    invoice_file_name VARCHAR(255),
    remarks TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    created_by UUID REFERENCES auth.users(id),

    -- 索引
    CONSTRAINT sales_invoices_seller_buyer_date_unique UNIQUE(seller_id, buyer_id, invoice_date, invoice_number)
);

-- 创建进项发票表
CREATE TABLE purchase_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES companies(id),
    buyer_id BIGINT NOT NULL REFERENCES companies(id),
    seller_name VARCHAR(255) NOT NULL,
    buyer_name VARCHAR(255) NOT NULL,
    payment_amount DECIMAL(15,2) NOT NULL CHECK (payment_amount >= 0),
    payment_date DATE NOT NULL,
    invoice_type VARCHAR(20) NOT NULL CHECK (invoice_type IN ('专票', '普票', '其他')),
    invoice_number VARCHAR(100),
    invoice_issued BOOLEAN DEFAULT FALSE,
    invoice_url TEXT,
    invoice_file_name VARCHAR(255),
    payment_voucher_url TEXT,
    payment_voucher_file_name VARCHAR(255),
    remarks TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    created_by UUID REFERENCES auth.users(id),

    -- 索引
    CONSTRAINT purchase_invoices_seller_buyer_date_unique UNIQUE(seller_id, buyer_id, payment_date, invoice_number)
);

-- 创建销售发票文件表（用于文件版本管理）
CREATE TABLE sales_invoice_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES sales_invoices(id) ON DELETE CASCADE,
    file_name VARCHAR(255) NOT NULL,
    file_path TEXT NOT NULL,
    file_size BIGINT NOT NULL,
    mime_type VARCHAR(100),
    storage_bucket VARCHAR(100) DEFAULT 'invoices',
    storage_path TEXT NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT NOW(),
    uploaded_by UUID REFERENCES auth.users(id)
);

-- 创建进项发票文件表（用于文件版本管理）
CREATE TABLE purchase_invoice_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES purchase_invoices(id) ON DELETE CASCADE,
    file_name VARCHAR(255) NOT NULL,
    file_path TEXT NOT NULL,
    file_size BIGINT NOT NULL,
    mime_type VARCHAR(100),
    file_type VARCHAR(20) NOT NULL CHECK (file_type IN ('invoice', 'payment_voucher')),
    storage_bucket VARCHAR(100) DEFAULT 'invoices',
    storage_path TEXT NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT NOW(),
    uploaded_by UUID REFERENCES auth.users(id)
);

-- 创建索引
CREATE INDEX idx_sales_invoices_seller_id ON sales_invoices(seller_id);
CREATE INDEX idx_sales_invoices_buyer_id ON sales_invoices(buyer_id);
CREATE INDEX idx_sales_invoices_date ON sales_invoices(invoice_date);
CREATE INDEX idx_sales_invoices_created_at ON sales_invoices(created_at);
CREATE INDEX idx_sales_invoices_amount ON sales_invoices(total_amount);

CREATE INDEX idx_purchase_invoices_seller_id ON purchase_invoices(seller_id);
CREATE INDEX idx_purchase_invoices_buyer_id ON purchase_invoices(buyer_id);
CREATE INDEX idx_purchase_invoices_date ON purchase_invoices(payment_date);
CREATE INDEX idx_purchase_invoices_created_at ON purchase_invoices(created_at);
CREATE INDEX idx_purchase_invoices_amount ON purchase_invoices(payment_amount);
CREATE INDEX idx_purchase_invoices_issued ON purchase_invoices(invoice_issued);

-- 创建更新时间戳的函数
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ language 'plpgsql';

-- 创建触发器自动更新 updated_at
CREATE TRIGGER update_sales_invoices_updated_at
    BEFORE UPDATE ON sales_invoices
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER update_purchase_invoices_updated_at
    BEFORE UPDATE ON purchase_invoices
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

