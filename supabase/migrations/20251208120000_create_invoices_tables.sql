    FOR SELECT USING (
        EXISTS (
            SELECT 1 FROM sales_invoices si
            WHERE si.id = sales_invoice_files.invoice_id
            AND (si.seller_id IN (SELECT company_id FROM user_companies WHERE user_id = auth.uid()) OR
                 si.buyer_id IN (SELECT company_id FROM user_companies WHERE user_id = auth.uid()))
